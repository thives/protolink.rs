//! Rendering of the Rust bindings and the LuaLS definitions. Both come from the same resolved model as the checker
//! rules, so they cannot disagree about a name or a signature.

use std::fmt::Write;

use crate::canonical::CANONICAL_VERSION;
use crate::lock::hex;
use crate::model::{
    ChildSlot, Contract, Enumeration, Execution, Module, Operation, Param, Resources, Type,
};

const HEADER: &str = "Generated by protolink-lua-plugin-gen. Do not edit by hand.";

/// Renders the Rust traits, enumerations, error types and child backend requirements of a contract.
///
/// The output depends on the `protolink_lua` crate for the child client trait. Every operation is a method on a trait
/// that the consumer implements, so a missing method is a compile error. There are no default bodies.
pub fn rust_bindings(contract: &Contract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// {HEADER}");
    let _ = writeln!(
        out,
        "// Contract {} ({}) version {}, canonical v{CANONICAL_VERSION}, digest sha256:{}",
        contract.name,
        contract.id,
        contract.version,
        hex(&contract.digest)
    );
    out.push('\n');
    let _ = writeln!(out, "pub const CONTRACT_NAME: &str = {:?};", contract.name);
    let _ = writeln!(out, "pub const CONTRACT_ID: &str = {:?};", contract.id);
    let _ = writeln!(
        out,
        "pub const CONTRACT_DIGEST: [u8; 32] = {};",
        byte_array(&contract.digest)
    );
    let _ = writeln!(
        out,
        "pub const PROFILE_FINGERPRINT: [u8; 32] = {};",
        byte_array(&contract.profile_fingerprint)
    );
    out.push('\n');
    if let Some(resources) = &contract.resources {
        render_resources(&mut out, resources);
    }

    for module in &contract.modules {
        render_module(&mut out, module);
    }
    for child in &contract.children {
        render_child(&mut out, child);
    }
    out
}

fn render_module(out: &mut String, module: &Module) {
    let module_pascal = pascal(&module.name);
    for enumeration in &module.enums {
        render_enum(out, &module_pascal, enumeration);
    }

    let error_name = format!("{module_pascal}Error");
    let _ = writeln!(
        out,
        "/// Errors that operations of module `{}` may return.",
        module.name
    );
    let _ = writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    let _ = writeln!(out, "pub enum {error_name} {{");
    for (name, _) in &module.errors {
        let _ = writeln!(out, "    {},", pascal(name));
    }
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "/// Native operations of module `{}`. Implement every method in firmware.",
        module.name
    );
    let _ = writeln!(out, "pub trait {module_pascal}Api {{");
    for operation in &module.operations {
        render_operation(out, &module_pascal, &error_name, operation);
    }
    out.push_str("}\n\n");
}

fn render_operation(
    out: &mut String,
    module_pascal: &str,
    error_name: &str,
    operation: &Operation,
) {
    let params: Vec<String> = operation
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, rust_param_type(module_pascal, p)))
        .collect();
    let results = result_type(module_pascal, &operation.results);
    let signature_params = if params.is_empty() {
        String::new()
    } else {
        format!(", {}", params.join(", "))
    };
    match operation.execution {
        Execution::Sync => {
            let _ = writeln!(
                out,
                "    fn {}(&mut self{signature_params}) -> Result<{results}, {error_name}>;",
                operation.name
            );
        }
        Execution::Async => {
            let _ = writeln!(
                out,
                "    fn {}(&mut self{signature_params}) -> impl core::future::Future<Output = Result<{results}, {error_name}>>;",
                operation.name
            );
        }
    }
}

fn render_enum(out: &mut String, module_pascal: &str, enumeration: &Enumeration) {
    let name = format!("{module_pascal}{}", pascal(&enumeration.name));
    let _ = writeln!(
        out,
        "/// Enumeration `{}`. Lua sees the symbol string.",
        enumeration.name
    );
    let _ = writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    let _ = writeln!(out, "pub enum {name} {{");
    for variant in &enumeration.variants {
        let _ = writeln!(out, "    {},", pascal(&variant.name));
    }
    out.push_str("}\n\n");
    let _ = writeln!(out, "impl {name} {{");
    out.push_str("    /// The Lua symbol of this value.\n");
    out.push_str("    pub const fn symbol(self) -> &'static str {\n        match self {\n");
    for variant in &enumeration.variants {
        let _ = writeln!(
            out,
            "            Self::{} => {:?},",
            pascal(&variant.name),
            variant.symbol
        );
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// Decodes a Lua symbol, rejecting anything that is not a variant.\n");
    out.push_str(
        "    pub fn from_symbol(symbol: &str) -> Option<Self> {\n        match symbol {\n",
    );
    for variant in &enumeration.variants {
        let _ = writeln!(
            out,
            "            {:?} => Some(Self::{}),",
            variant.symbol,
            pascal(&variant.name)
        );
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n\n");
}

/// The compile-time resource envelope. The firmware builds its node configuration from these constants.
fn render_resources(out: &mut String, r: &Resources) {
    out.push_str("pub mod resources {\n");
    let _ = writeln!(
        out,
        "    pub const MAX_ARTIFACT_BYTES: u32 = {};",
        r.max_artifact_bytes
    );
    let _ = writeln!(
        out,
        "    pub const MAX_CHUNK_BYTES: u32 = {};",
        r.max_chunk_bytes
    );
    let _ = writeln!(out, "    pub const MAX_UPLOADS: u32 = {};", r.max_uploads);
    let _ = writeln!(out, "    pub const MAX_SESSIONS: u32 = {};", r.max_sessions);
    let _ = writeln!(
        out,
        "    pub const MAX_EXECUTIONS: u32 = {};",
        r.max_executions
    );
    let _ = writeln!(
        out,
        "    pub const MAX_ANSWER_BYTES: u32 = {};",
        r.max_answer_bytes
    );
    let _ = writeln!(out, "    pub const SLICE_FUEL: u32 = {};", r.slice_fuel);
    let _ = writeln!(out, "    pub const TOTAL_FUEL: u64 = {};", r.total_fuel);
    let _ = writeln!(out, "    pub const MAX_FRAMES: u32 = {};", r.max_frames);
    let _ = writeln!(out, "    pub const MAX_OBJECTS: u32 = {};", r.max_objects);
    let _ = writeln!(
        out,
        "    pub const MAX_HEAP_BYTES: u32 = {};",
        r.max_heap_bytes
    );
    let _ = writeln!(
        out,
        "    pub const SESSION_IDLE_MS: u32 = {};",
        r.session_idle_ms
    );
    let _ = writeln!(
        out,
        "    pub const MAX_ARTIFACTS: u32 = {};",
        r.max_artifacts
    );
    let _ = writeln!(
        out,
        "    pub const RETIRED_WINDOW: u32 = {};",
        r.retired_window
    );
    let _ = writeln!(
        out,
        "    pub const MAX_CHILD_TASKS: u32 = {};",
        r.max_child_tasks
    );
    let _ = writeln!(
        out,
        "    pub const CALL_TIMEOUT_MS: u32 = {};",
        r.call_timeout_ms
    );
    let _ = writeln!(out, "    pub const CLEANUP_MS: u32 = {};", r.cleanup_ms);
    let _ = writeln!(
        out,
        "    pub const MAX_REQUEST_BYTES: u32 = {};",
        r.max_request_bytes
    );
    out.push_str("}\n\n");
}

fn render_child(out: &mut String, child: &ChildSlot) {
    let slot = pascal(&child.name);
    let upper = child.name.to_ascii_uppercase();
    let _ = writeln!(
        out,
        "/// Child slot `{}` runs contract `{}`. Firmware must implement this backend to compile.",
        child.name, child.child
    );
    let _ = writeln!(
        out,
        "pub trait {slot}ChildBackend: protolink_lua::child::ChildClient {{}}"
    );
    let _ = writeln!(out, "pub const {upper}_SLOT_ID: u32 = {};", child.id);
    let _ = writeln!(out, "pub const {upper}_INDEX: u8 = {};", child.index);
    let _ = writeln!(
        out,
        "pub const {upper}_CHILD_DIGEST: [u8; 32] = {};",
        byte_array(&child.child_digest)
    );
    let _ = writeln!(
        out,
        "pub const {upper}_MAX_CAPTURE_BYTES: u32 = {};",
        child.max_capture_bytes
    );
    let _ = writeln!(
        out,
        "pub const {upper}_MAX_RESULT_BYTES: u32 = {};",
        child.max_result_bytes
    );
    out.push('\n');
}

/// Renders LuaLS definitions for the remote surface of a contract. These are documentation and completion only. They
/// do not enforce where code runs; the generated checker does.
pub fn lua_definitions(contract: &Contract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "---@meta");
    let _ = writeln!(out, "-- {HEADER}");
    let _ = writeln!(
        out,
        "-- Contract {} version {}, digest sha256:{}",
        contract.name,
        contract.version,
        hex(&contract.digest)
    );
    out.push_str("-- Definitions document the remote surface. They do not enforce placement.\n\n");
    for module in &contract.modules {
        let _ = writeln!(out, "{0} = {0} or {{}}", module.name);
        for enumeration in &module.enums {
            let symbols: Vec<String> = enumeration
                .variants
                .iter()
                .map(|v| format!("{:?}", v.symbol))
                .collect();
            let _ = writeln!(
                out,
                "---@alias {}.{} {}",
                module.name,
                enumeration.name,
                symbols.join("|")
            );
            let entries: Vec<String> = enumeration
                .variants
                .iter()
                .map(|v| format!("{} = {:?}", v.name, v.symbol))
                .collect();
            let _ = writeln!(
                out,
                "{}.{} = {{ {} }}",
                module.name,
                enumeration.name,
                entries.join(", ")
            );
        }
        for operation in &module.operations {
            let mut names = Vec::new();
            for param in &operation.params {
                names.push(param.name.clone());
                let _ = writeln!(
                    out,
                    "---@param {} {}",
                    param.name,
                    lua_type(&module.name, param)
                );
            }
            let returns: Vec<String> = operation
                .results
                .iter()
                .map(|r| lua_type(&module.name, r))
                .collect();
            if !returns.is_empty() {
                let _ = writeln!(out, "---@return {}", returns.join(", "));
            }
            let _ = writeln!(
                out,
                "function {}.{}({}) end",
                module.name,
                operation.name,
                names.join(", ")
            );
        }
        out.push('\n');
    }
    for child in &contract.children {
        let _ = writeln!(out, "---@class {}ChildTask", pascal(&child.name));
        let _ = writeln!(
            out,
            "---@field await fun(self: {}ChildTask): any",
            pascal(&child.name)
        );
        let _ = writeln!(out, "---@class {}ChildSlot", pascal(&child.name));
        let _ = writeln!(
            out,
            "---@field spawn fun(self: {0}ChildSlot, body: fun(...): any, ...: any): {0}ChildTask",
            pascal(&child.name)
        );
        let _ = writeln!(out, "---@type {}ChildSlot", pascal(&child.name));
        let _ = writeln!(
            out,
            "{} = nil -- supplied by the destination node",
            child.name
        );
    }
    out
}

fn rust_type(module_pascal: &str, ty: &Type) -> String {
    match ty {
        Type::Nil => "()".to_string(),
        Type::Boolean => "bool".to_string(),
        Type::Integer => "i64".to_string(),
        Type::Float => "f64".to_string(),
        Type::Bytes { .. } => "Vec<u8>".to_string(),
        Type::Enum { reference } => {
            let enum_name = reference.rsplit('.').next().unwrap_or(reference);
            format!("{module_pascal}{}", pascal(enum_name))
        }
    }
}

fn rust_param_type(module_pascal: &str, param: &Param) -> String {
    match &param.ty {
        Type::Bytes { .. } => "&[u8]".to_string(),
        other => rust_type(module_pascal, other),
    }
}

fn result_type(module_pascal: &str, results: &[Param]) -> String {
    match results {
        [] => "()".to_string(),
        [one] => rust_type(module_pascal, &one.ty),
        many => {
            let parts: Vec<String> = many
                .iter()
                .map(|p| rust_type(module_pascal, &p.ty))
                .collect();
            format!("({})", parts.join(", "))
        }
    }
}

fn lua_type(module: &str, param: &Param) -> String {
    match &param.ty {
        Type::Nil => "nil".to_string(),
        Type::Boolean => "boolean".to_string(),
        Type::Integer => "integer".to_string(),
        Type::Float => "number".to_string(),
        Type::Bytes { .. } => "string".to_string(),
        Type::Enum { reference } => format!(
            "{module}.{}",
            reference.rsplit('.').next().unwrap_or(reference)
        ),
    }
}

fn byte_array(bytes: &[u8]) -> String {
    let parts: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
    format!("[{}]", parts.join(", "))
}

/// `snake_case` or `dotted.name` to `PascalCase`.
pub(crate) fn pascal(name: &str) -> String {
    name.split(['_', '.', '-'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
