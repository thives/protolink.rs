//! Thin, VM-neutral execution protocol for distributed Lua tasks.
//!
//! The crate owns the wire messages, the remote-data v1 value codec, the execution lifecycle, the per-session
//! admission ledger and the child client interface. It does not depend on a Lua VM, a compiler, a board support
//! package, firmware or an application. Transport is injected: nodes and proxies drive Protolink themselves.
//!
//! The authoritative schema is `proto/lua/execution/v1/execution.proto` in the `protolink-lua-api` crate. The wire messages
//! are re-exported from that crate as [`wire`].
#![no_std]
#![forbid(unsafe_code)]
#![deny(missing_docs)]

extern crate alloc;

pub mod child;
pub mod codec;
pub mod flow;
pub mod frame;
pub mod ledger;
pub mod lifecycle;
pub mod value;

#[cfg(feature = "testing")]
pub mod testing;

/// Messages of `lua.execution.v1`, generated by `protolink-lua-api`. The messages are under [`wire::v1`].
pub use protolink_lua_api::execution::wire;

/// The revision of the execution semantics this crate implements, reported in `DescribeResponse.protocol_revision`.
/// Revision 3 adds method-bound replay, execution-session ownership, mutation receipts, release disposition and
/// the advertised session idle timeout. Revision 4 replays the answers of final calls from a bounded table, advertised
/// as `final_replay_slots`, and counts an active retransmission as session activity. A caller refuses a peer with
/// another revision before uploading or starting.
pub const PROTOCOL_REVISION: u32 = 4;
